# Held in the session between "send code" and "verify code" so the number and
# name being verified are exactly what the code was sent for — never trusted
# from the verify form itself.
PENDING_KEY = 'setup_pending'
TEST_CODE_KEY = 'setup_test_code'

NAME_MAX_LENGTH = 150


def _record_for(user):
    profile = getattr(user, 'clergy_profile', None)
    return profile.record if profile is not None else None


def _home_url_name(user):
    return 'registrar:dashboard' if user.is_staff else 'clergy:dashboard'


def _clean_name(raw):
    name = re.sub(r'\s+', ' ', raw or '').strip()
    if not name:
        raise ValueError('Please enter your full name.')
    if len(name) > NAME_MAX_LENGTH:
        raise ValueError(f'Your name is too long (the limit is {NAME_MAX_LENGTH} characters).')
    if not re.search(r'[^\W\d_]', name):
        raise ValueError('Please enter your real, full name.')
    return name


def _send_code(request, user, e164):
    """Texts a code for `e164`; on success remembers it as the pending number.
    Returns True if sent, otherwise flashes why and returns False."""
    try:
        test_code = otp.issue(user, 'phone_verify', e164)
    except otp.OtpError as exc:
        messages.error(request, str(exc))
        return False
    if test_code:
        request.session[TEST_CODE_KEY] = test_code
    return True


@never_cache
@login_required(login_url='index')
def activate(request):
    user = request.user
    stage = setup.pending_stage(user)
    if stage is None:
        return redirect(_home_url_name(user))

    record = _record_for(user)
    security = UserSecurity.objects.filter(user=user).first()
    pending = request.session.get(PENDING_KEY)

    if request.method == 'POST':
        action = request.POST.get('action')

        if stage == setup.PHONE and action == 'send_code':
            try:
                name = _clean_name(request.POST.get('name'))
                e164 = normalize_ph_mobile(request.POST.get('phone'))
            except ValueError as exc:
                messages.error(request, str(exc))
                return redirect('activate')
            unavailable = otp.number_unavailable(user, e164)
            if unavailable:
                messages.error(request, unavailable)
                return redirect('activate')
            if _send_code(request, user, e164):
                request.session[PENDING_KEY] = {'phone': e164, 'name': name}
            return redirect('activate')

        if stage == setup.PHONE and action == 'resend' and pending:
            _send_code(request, user, pending['phone'])
            return redirect('activate')

        if stage == setup.PHONE and action == 'change_number':
            request.session.pop(PENDING_KEY, None)
            request.session.pop(TEST_CODE_KEY, None)
            otp.release_pending(user, ('phone_verify',))
            return redirect('activate')

        if stage == setup.PHONE and action == 'verify_code' and not pending:
            messages.error(request, 'Press Send code first, then enter the code we text you.')
            return redirect('activate')

        if stage == setup.PHONE and action == 'verify_code' and pending:
            try:
                otp.verify(user, 'phone_verify', pending['phone'], request.POST.get('code'))
            except otp.OtpError as exc:
                messages.error(request, str(exc))
                return redirect('activate')
            try:
                with transaction.atomic():
                    if record is not None:
                        record.name = pending['name']
                        record.phone = pending['phone']
                        record.save(update_fields=['name', 'phone'])
                    else:
                        # Registrar staff have no clergy record. Their name lives on
                        # the user (first_name holds the whole name), which is what
                        # the sidebar and "Generated by" on reports already read.
                        user.first_name = pending['name']
                        user.last_name = ''
                        user.save(update_fields=['first_name', 'last_name'])
                    security, _ = UserSecurity.objects.get_or_create(user=user)
                    security.phone = pending['phone']
                    security.phone_verified_at = timezone.now()
                    security.phone_verified_via = 'test' if sms.is_test_backend() else 'sms'
                    security.save(update_fields=['phone', 'phone_verified_at', 'phone_verified_via'])
            except IntegrityError:
                # Someone else verified this number between our check and now.
                messages.error(request, 'That number is already registered to another account.')
                request.session.pop(PENDING_KEY, None)
                return redirect('activate')
            request.session.pop(PENDING_KEY, None)
            request.session.pop(TEST_CODE_KEY, None)
            if setup.pending_stage(user) is None:
                messages.success(request, 'Your number is verified.')
                response = redirect(_home_url_name(user))
                devices.trust(response, request, user)
                return response
            messages.success(request, 'Your number is verified. One last step: choose your own password.')
            return redirect('activate')

        if stage == setup.PASSWORD and action == 'set_password':
            new = request.POST.get('new_password', '')
            confirm = request.POST.get('confirm_password', '')
            if new != confirm:
                messages.error(request, 'The two passwords do not match.')
            elif user.check_password(new):
                messages.error(request, 'Choose a different password from the one you were given.')
            elif validate_password_or_flag_errors(request, new, user=user):
                now = timezone.now()
                user.set_password(new)
                user.save(update_fields=['password'])
                keep_signed_in_after_password_change(request, user)
                security.password_changed_at = now
                if security.activated_at is None:
                    security.activated_at = now
                security.setup_expires_at = None
                security.save(update_fields=['password_changed_at', 'activated_at', 'setup_expires_at'])
                notifications.account_activated(user)
                messages.success(request, 'Account activated. Welcome!')
                response = redirect(_home_url_name(user))
                devices.trust(response, request, user)  # they just proved this browser with their phone
                return response
            return redirect('activate')

        return redirect('activate')

    context = {
        'stage': stage,
        'step': 3 if stage == setup.PASSWORD else (2 if pending else 1),
        'name': (pending or {}).get('name') or (record.name if record else user.get_full_name()),
        'phone': prefill_phone(pending),
        'sent': bool(pending),
        'pending_phone_masked': mask(pending['phone']) if pending else None,
        'test_code': request.session.get(TEST_CODE_KEY) if sms.is_test_backend() else None,
        'test_mode': sms.is_test_backend(),
        'reverifying': security is not None and bool(security.phone) and stage == setup.PHONE,
        # Drives the Send/Resend button: its countdown, and whether today's codes are used up.
        'resend': otp.resend_status(user, 'phone_verify', pending['phone'] if pending else ''),
    }
    return render(request, 'activate.html', context)


def prefill_phone(pending):
    """The number the code was just sent to, shown back to them. Never the number
    saved earlier: when someone has to verify again, that number was never
    confirmed (it may have been typed in test mode, or wrongly), and pre-filling it
    meant one press of Send texted it, and used up an attempt, without the person
    ever re-entering anything."""
    return display(pending['phone']) if pending else ''


# --- Security: username, password, number, trusted devices ----------------
#
# One set of actions behind both portals. The registrar's "My Profile" page and
# the clergy member's "Security" tab show the same sections (security_context)
# and post here; every action ends back on that page.

CHANGE_PENDING_KEY = 'phone_change_pending'
CHANGE_TEST_CODE_KEY = 'phone_change_test_code'


def profile_security_url(user):
    """Where this user's security settings live."""
    if user.is_staff:
        return reverse('registrar:my_profile')
    return reverse('clergy:my_profile') + '?tab=security'


def _clear_change(request):
    request.session.pop(CHANGE_PENDING_KEY, None)
    request.session.pop(CHANGE_TEST_CODE_KEY, None)


def security_context(request):
    """What the shared security sections need to render."""
    user = request.user
    security = UserSecurity.objects.get(user=user)
    pending = request.session.get(CHANGE_PENDING_KEY)
    current = devices.current_device(request, user)
    trusted = TrustedDevice.objects.filter(user=user, expires_at__gt=timezone.now())
    return {
        'card_class': 'panel' if user.is_staff else 'section-card',
        'masked_phone': mask(security.phone) if security.phone else None,
        'sent': bool(pending),
        'pending_masked': mask(pending['phone']) if pending else None,
        'pending_display': display(pending['phone']) if pending else '',
        'resend': otp.resend_status(user, 'phone_change', pending['phone'] if pending else ''),
        'test_mode': sms.is_test_backend(),
        'test_code': request.session.get(CHANGE_TEST_CODE_KEY) if sms.is_test_backend() else None,
        'trusted_devices': [{'device': d, 'is_current': current is not None and d.pk == current.pk} for d in trusted],
        'other_devices': trusted.exclude(pk=current.pk if current else None).exists(),
    }


def password_confirmed(request):
    """Gate for changes that could lock the owner out or redirect their codes, and
    for taking a backup out of the system: the current password (the POST field
    `current_password`) must be re-entered, so a hijacked session alone isn't enough.
    Wrong guesses count toward the same lockout as the sign-in page."""
    user = request.user
    if login_throttle.is_locked_out(user.username):
        messages.error(request, login_throttle.LOCKOUT_MESSAGE)
        return False
    if not user.check_password(request.POST.get('current_password', '')):
        _, failures = login_throttle.register_failure(user.username)
        locked = failures >= login_throttle.MAX_ATTEMPTS
        security_log.password_check_failed(request, user.username, failures, locked=locked)
        if locked:
            notifications.sign_in_locked(request, user)
        messages.error(request, 'Your current password is incorrect.')
        return False
    login_throttle.clear(user.username)
    return True


def _send_number_code(request, security):
    user = request.user
    try:
        e164 = normalize_ph_mobile(request.POST.get('phone'))
    except ValueError as exc:
        messages.error(request, str(exc))
        return
    unavailable = otp.number_unavailable(user, e164)
    if e164 == security.phone:
        messages.error(request, 'That is already your number.')
    elif unavailable:
        messages.error(request, unavailable)
    else:
        try:
            test_code = otp.issue(user, 'phone_change', e164)
        except otp.OtpError as exc:
            messages.error(request, str(exc))
        else:
            request.session[CHANGE_PENDING_KEY] = {'phone': e164}
            if test_code:
                request.session[CHANGE_TEST_CODE_KEY] = test_code


def _confirm_number_change(request, security, pending):
    user = request.user
    try:
        otp.verify(user, 'phone_change', pending['phone'], request.POST.get('code'))
    except otp.OtpError as exc:
        messages.error(request, str(exc))
        return
    try:
        with transaction.atomic():
            security.phone = pending['phone']
            security.phone_verified_at = timezone.now()
            security.phone_verified_via = 'test' if sms.is_test_backend() else 'sms'
            security.save(update_fields=['phone', 'phone_verified_at', 'phone_verified_via'])
            record = _record_for(user)
            if record is not None:
                record.phone = pending['phone']
                record.save(update_fields=['phone'])
            # Browsers trusted under the old number no longer vouch for
            # whoever holds the new one; keep only the one in use now.
            current = devices.current_device(request, user)
            TrustedDevice.objects.filter(user=user).exclude(pk=current.pk if current else None).delete()
            audit.record(user, user, 'phone_changed')
            notifications.phone_changed(user, pending['phone'])
    except IntegrityError:
        messages.error(request, 'That number is already registered to another account.')
    else:
        messages.success(request, 'Your mobile number has been changed. Other devices will ask for a code next time.')
    _clear_change(request)


def _change_username(request):
    user = request.user
    new = (request.POST.get('username') or '').strip()
    try:
        if not new:
            raise ValidationError('Please enter a username.')
        if len(new) > user._meta.get_field('username').max_length:
            raise ValidationError('That username is too long.')
        user.username_validator(new)
    except ValidationError as exc:
        messages.error(request, ' '.join(exc.messages) or 'That username is not allowed.')
        return
    if new == user.username:
        messages.error(request, 'That is already your username.')
    elif get_user_model().objects.filter(username__iexact=new).exclude(pk=user.pk).exists():
        messages.error(request, 'That username is already taken.')
    else:
        old, user.username = user.username, new
        try:
            with transaction.atomic():
                user.save(update_fields=['username'])
                audit.record(user, user, 'username_changed', f'{old} → {new}')
                notifications.username_changed(user, old, new)
        except IntegrityError:
            user.username = old
            messages.error(request, 'That username is already taken.')
        else:
            messages.success(request, 'Your username has been changed.')


def _change_password(request):
    user = request.user
    new = request.POST.get('new_password', '')
    if new != request.POST.get('confirm_password', ''):
        messages.error(request, 'The two new passwords do not match.')
    elif user.check_password(new):
        messages.error(request, 'Choose a different password from your current one.')
    elif validate_password_or_flag_errors(request, new, user=user):
        user.set_password(new)
        user.save(update_fields=['password'])
        keep_signed_in_after_password_change(request, user)
        UserSecurity.objects.filter(user=user).update(password_changed_at=timezone.now())
        notifications.password_changed(request, user)
        messages.success(request, 'Your password has been changed.')


def _update_name(request):
    """Registrar staff only — clergy edit their name on their record. The name is
    what reports are 'Generated by', so a change is logged with the old name."""
    user = request.user
    try:
        new = _clean_name(request.POST.get('name'))
    except ValueError as exc:
        messages.error(request, str(exc))
        return
    old = user.get_full_name().strip()
    if new == old:
        return
    user.first_name, user.last_name = new, ''
    with transaction.atomic():
        user.save(update_fields=['first_name', 'last_name'])
        audit.record(user, user, 'name_changed', f'{old or user.username} → {new}')
    messages.success(request, 'Your name has been updated.')


@login_required(login_url='index')
def my_security(request):
    """Endpoint for every security action. Changing the number needs the account
    password AND a code texted to the NEW number (so neither a hijacked session
    nor a number nobody holds is enough). When the old phone is lost there is no
    self-service path: that is the registrar's in-person reset."""
    user = request.user
    back = redirect(profile_security_url(user))
    if request.method != 'POST':
        return back

    security = UserSecurity.objects.get(user=user)
    pending = request.session.get(CHANGE_PENDING_KEY)
    action = request.POST.get('action')

    if action == 'send_change_code':
        if password_confirmed(request):
            _send_number_code(request, security)
    elif action == 'resend_change' and pending:
        try:
            test_code = otp.issue(user, 'phone_change', pending['phone'])
        except otp.OtpError as exc:
            messages.error(request, str(exc))
        else:
            if test_code:
                request.session[CHANGE_TEST_CODE_KEY] = test_code
            messages.success(request, 'A new code is on its way.')
    elif action == 'cancel_change':
        _clear_change(request)
        otp.release_pending(user, ('phone_change',))
    elif action == 'verify_change_code' and not pending:
        messages.error(request, 'Press Send code first, then enter the code we text you.')
    elif action == 'verify_change_code' and pending:
        _confirm_number_change(request, security, pending)
    elif action == 'change_username':
        if password_confirmed(request):
            _change_username(request)
    elif action == 'change_password':
        if password_confirmed(request):
            _change_password(request)
    elif action == 'update_name' and user.is_staff and _record_for(user) is None:
        _update_name(request)
    elif action == 'revoke_device':
        device_id = request.POST.get('device_id', '')
        device = None
        if device_id.isdigit():  # a tampered, non-numeric id is just "not found"
            device = TrustedDevice.objects.filter(user=user, pk=int(device_id)).first()
        if device is not None:
            device.delete()
            notifications.device_removed(user, device.label)
        messages.success(request, 'Device removed. It will ask for a code the next time it signs in.' if device else 'That device was already removed.')
    elif action == 'revoke_others':
        current = devices.current_device(request, user)
        count, _ = TrustedDevice.objects.filter(user=user).exclude(pk=current.pk if current else None).delete()
        if count:
            notifications.other_devices_removed(user, count)
        messages.success(request, f'Removed {count} other device{"" if count == 1 else "s"}.')
    return back


# --- Forgot password ------------------------------------------------------
#
# Three screens on one URL, driven by what the session holds: enter the number
# and a code, then choose a new password. Nothing a visitor sees depends on
# whether the number belongs to an account (see accounts.forgot), so this page
# can't be used to find out who is registered.

logger = logging.getLogger(__name__)

FORGOT_KEY = 'forgot_pending'               # {'phone', 'wrong'}: a code was requested for this number
FORGOT_TEST_CODE_KEY = 'forgot_test_code'
FORGOT_OK_KEY = 'forgot_verified'           # {'user_id', 'phone', 'at'}: the code was right
FORGOT_VERIFIED_MAX_AGE_SECONDS = 10 * 60
FORGOT_MAX_WRONG = 3
MODEL_BACKEND = 'django.contrib.auth.backends.ModelBackend'


def _forgot_clear(request):
    for key in (FORGOT_KEY, FORGOT_TEST_CODE_KEY, FORGOT_OK_KEY):
        request.session.pop(key, None)


def _forgot_send(request, e164):
    """Counts the request, and texts a code if the number belongs to an account that
    may reset this way. True unless a limit stopped it. A code that couldn't be
    issued for a real account (SMS down, a cap) is logged, not shown: saying so would
    tell the visitor the number is registered."""
    try:
        forgot.record_request(e164)
    except forgot.ForgotLimit as exc:
        messages.error(request, str(exc))
        return False
    request.session.pop(FORGOT_TEST_CODE_KEY, None)
    user = forgot.eligible_user(e164)
    if user is not None:
        try:
            test_code = otp.issue(user, 'password_reset', e164)
        except otp.OtpError as exc:
            logger.warning('Forgot-password code not sent for user %s: %s', user.pk, exc)
        else:
            if test_code:
                request.session[FORGOT_TEST_CODE_KEY] = test_code
    return True


def _forgot_verified_user(request):
    """The account whose code was just accepted, while that approval is fresh."""
    ok = request.session.get(FORGOT_OK_KEY)
    if not ok or timezone.now().timestamp() - ok['at'] > FORGOT_VERIFIED_MAX_AGE_SECONDS:
        return None
    user = forgot.eligible_user(ok['phone'])
    return user if user is not None and user.pk == ok['user_id'] else None


def _forgot_check_code(request, pending):
    """Right or wrong, and the visitor is told only that — never how many guesses the
    real code has left, which would differ for a number with no account."""
    user = forgot.eligible_user(pending['phone'])
    if user is not None:
        try:
            otp.verify(user, 'password_reset', pending['phone'], request.POST.get('code'))
        except otp.OtpError:
            pass
        else:
            request.session[FORGOT_OK_KEY] = {'user_id': user.pk, 'phone': pending['phone'], 'at': timezone.now().timestamp()}
            request.session.pop(FORGOT_KEY, None)
            request.session.pop(FORGOT_TEST_CODE_KEY, None)
            return
    pending['wrong'] = pending.get('wrong', 0) + 1
    if pending['wrong'] >= FORGOT_MAX_WRONG:
        _forgot_clear(request)
        messages.error(request, 'Too many wrong codes. Please start again.')
    else:
        request.session[FORGOT_KEY] = pending
        messages.error(request, "That code isn't right, or it has expired. Check it and try again.")


def _forgot_set_password(request, user):
    new = request.POST.get('new_password', '')
    if new != request.POST.get('confirm_password', ''):
        messages.error(request, 'The two passwords do not match.')
        return None
    if user.check_password(new):
        messages.error(request, 'Choose a different password from your current one.')
        return None
    if not validate_password_or_flag_errors(request, new, user=user):
        return None

    now = timezone.now()
    with transaction.atomic():
        user.set_password(new)
        user.save(update_fields=['password'])
        UserSecurity.objects.filter(user=user).update(password_changed_at=now)
        # Whoever else may have had this account — any other browser, any code still
        # out — is shut out; this browser is the one the owner just proved with their phone.
        TrustedDevice.objects.filter(user=user).delete()
        OtpChallenge.objects.filter(user=user, consumed_at__isnull=True).update(consumed_at=now)
        audit.record(user, user, 'password_reset', 'via mobile number')
        notifications.password_reset(request, user)
    login_throttle.clear(user.username)   # a forgotten password usually means failed attempts first
    _forgot_clear(request)

    user.backend = MODEL_BACKEND
    auth_login(request, user)
    messages.success(request, 'Your password has been changed and you are signed in.')
    response = redirect(_home_url_name(user))
    devices.trust(response, request, user)
    return response


@never_cache
def forgot_password(request):
    if request.user.is_authenticated:
        return redirect(_home_url_name(request.user))

    verified_user = _forgot_verified_user(request)
    pending = request.session.get(FORGOT_KEY)
    if verified_user is None:
        request.session.pop(FORGOT_OK_KEY, None)   # expired or no longer valid

    if request.method == 'POST':
        action = request.POST.get('action')

        if verified_user is not None:
            if action == 'set_password':
                response = _forgot_set_password(request, verified_user)
                if response is not None:
                    return response
            elif action == 'cancel':
                _forgot_clear(request)
        elif action == 'send_code' and not pending:
            try:
                e164 = normalize_ph_mobile(request.POST.get('phone'))
            except ValueError as exc:
                messages.error(request, str(exc))
            else:
                if _forgot_send(request, e164):
                    request.session[FORGOT_KEY] = {'phone': e164, 'wrong': 0}
        elif action == 'resend' and pending:
            if _forgot_send(request, pending['phone']):
                request.session[FORGOT_KEY] = {'phone': pending['phone'], 'wrong': 0}
        elif action == 'change_number':
            _forgot_clear(request)
        elif action == 'verify_code':
            if pending:
                _forgot_check_code(request, pending)
            else:
                messages.error(request, 'Press Send code first, then enter the code we text you.')
        return redirect('forgot_password')

    stage = 'password' if verified_user is not None else ('code' if pending else 'number')
    return render(request, 'forgot_password.html', {
        'stage': stage,
        'step': {'number': 1, 'code': 2, 'password': 3}[stage],
        'sent': bool(pending),
        'phone': display(pending['phone']) if pending else '',
        'pending_masked': mask(pending['phone']) if pending else None,
        'resend': forgot.status(pending['phone'] if pending else ''),
        'test_mode': sms.is_test_backend(),
        'test_code': request.session.get(FORGOT_TEST_CODE_KEY) if sms.is_test_backend() else None,
    })
